"""Deterministically compile the attributed, editable travel facts; no network at runtime."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def lua(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + (str(int(k)) if str(k).isdigit() else lua(k)) + ']=' + lua(v)
                              for k, v in sorted(value.items(), key=lambda item: str(item[0]))) + '}'
    if isinstance(value, list):
        return '{' + ','.join(map(lua, value)) + '}'
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return str(value)

facts = json.loads((ROOT / 'Assets/Travel/travel-facts.json').read_text(encoding='utf8'))
(ROOT / 'Modules/TravelData.lua').write_text(
    '-- Generated by tools/build-travel-data.py. Source/terms: Assets/Travel/README.md.\n'
    'local _,AUI=...\nAUI.TravelData=' + lua(facts) + '\n', encoding='utf8')
