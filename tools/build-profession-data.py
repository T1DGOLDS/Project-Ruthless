"""Compile reviewed factual profession records. No network required to build."""
import argparse, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def lua(value):
    if value is None: return 'nil'
    if value is True: return 'true'
    if value is False: return 'false'
    if isinstance(value, (int, float)): return str(value)
    if isinstance(value, str):
        return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r') + '"'
    if isinstance(value, list): return '{' + ','.join(lua(v) for v in value) + '}'
    return '{' + ','.join('[' + (str(int(k)) if k.isdigit() else lua(k)) + ']=' + lua(v) for k,v in sorted(value.items())) + '}'

def main():
    args = argparse.ArgumentParser(); args.add_argument('--check', action='store_true'); args = args.parse_args()
    facts = json.loads((ROOT/'Assets/Professions/facts.json').read_text(encoding='utf-8'))
    assert len(facts['professions']) == 12
    for prof in facts['professions'].values():
        ids = set()
        for r in prof['recipes']:
            assert r['id'] > 0 and r['id'] not in ids; ids.add(r['id'])
            for material in r.get('materials', []): assert material['id'] > 0 and material['quantity'] > 0
        for step in prof['steps']: assert 1 <= step['from'] < step['to'] <= 300
    # Table allocation is delayed until the workspace is first opened.
    data = '-- Generated by tools/build-profession-data.py; factual records only.\nlocal _,AUI=...\nfunction AUI:LoadProfessionFacts()\n return ' + lua(facts) + '\nend\n'
    target = ROOT/'Modules/ProfessionData.lua'
    if args.check:
        assert target.read_text(encoding='utf-8') == data, 'Profession data needs regeneration'
    else: target.write_text(data, encoding='utf-8', newline='\n')
    print('Profession facts:', facts['summary'])

if __name__ == '__main__': main()
